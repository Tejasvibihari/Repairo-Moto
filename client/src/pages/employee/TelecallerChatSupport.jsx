export default function TelecallerChatSupport() {
    const [orders, setOrders] = useState([]);
    const [selected, setSelected] = useState(null);
    const [messages, setMessages] = useState([]);
    const [messagesOrderId, setMessagesOrderId] = useState(null); // which chat `messages` belongs to
    const [text, setText] = useState('');
    const [loading, setLoading] = useState(true);
    const [sending, setSending] = useState(false);
    const [error, setError] = useState('');

    // AI quick replies
    const [suggestions, setSuggestions] = useState([]);
    const [suggesting, setSuggesting] = useState(false);
    const [suggestError, setSuggestError] = useState('');
    const [suggestLang, setSuggestLang] = useState(''); // English | Hindi | Hinglish

    const endRef = useRef(null);
    const inputRef = useRef(null);
    const suggestReq = useRef(0); // ignores stale responses when the chat/message changes
    const selectedIdRef = useRef(null);
    const socketRef = useRef(null);
    const editedFromSuggestion = useRef(false);

    const location = useLocation();
    const navigate = useNavigate();

    // Unread tracking (WhatsApp style)
    const [windowActive, setWindowActive] = useState(isWindowActive);
    const windowActiveRef = useRef(windowActive);
    windowActiveRef.current = windowActive;
    const [alertPerm, setAlertPerm] = useState(notificationPermission());
    const [alertHint, setAlertHint] = useState('');

    // True while the agent is sending suggested messages one after another (follow-up mode)
    const [chain, setChain] = useState(false);

    // Same token choice as axiosClient: the employee session wins, otherwise admin
    const token = useSelector((s) => (s.employeeAuth?.isAuthenticated ? s.auth.employeeToken : s.auth.adminToken || s.auth.employeeToken));
    const [live, setLive] = useState(false);

    selectedIdRef.current = selected?.orderId || null;

    const lastMessage = messages[messages.length - 1];
    const chatLoaded = !!selected && messagesOrderId === selected.orderId;
    // Number of agent messages sent in a row after the customer's last message
    let agentRun = 0;
    for (let i = messages.length - 1; i >= 0 && messages[i].senderType !== 'user'; i--) agentRun++;
    // Suggest when the customer spoke last, or (follow-up mode) after the agent sent a suggested message.
    const needsReply = chatLoaded && lastMessage?.senderType === 'user';
    const wantsFollowUp = chatLoaded && chain && !!lastMessage && lastMessage.senderType !== 'user' && agentRun < MAX_AGENT_CHAIN;
    const wantsSuggestions = needsReply || wantsFollowUp;

    // silent = background refresh (no spinner, keeps the current selection)
    const loadOrders = async (silent = false) => {
        if (!silent) setLoading(true);
        try {
            const data = await chatApi.orders();
            setOrders(data || []);
            setSelected((current) => {
                // Don't auto-open the first chat: opening it would silently mark its messages as read
                if (!current) return null;
                const fresh = (data || []).find((o) => o.orderId === current.orderId);
                // keep the same object when nothing changed so effects don't re-run
                return fresh && (fresh.status !== current.status || fresh.customerName !== current.customerName) ? { ...current, ...fresh } : current;
            });
            if (!silent) setError('');
        } catch (err) {
            if (!silent) setError(errMsg(err, 'Could not load conversations.'));
        } finally {
            if (!silent) setLoading(false);
        }
    };

    const loadMessages = async (order, silent = false) => {
        try {
            const data = await chatApi.messages(order.orderId);
            if (selectedIdRef.current !== order.orderId) return; // user switched chats meanwhile
            setMessages(data.messages || []);
            setMessagesOrderId(order.orderId);
        } catch (err) {
            if (!silent) setError(errMsg(err, 'Could not load messages.'));
        }
    };

    const loadSuggestions = async (orderId) => {
        const reqId = ++suggestReq.current;
        setSuggesting(true);
        setSuggestError('');
        setSuggestions([]);
        setSuggestLang('');
        try {
            const data = await chatApi.suggestions(orderId);
            if (reqId !== suggestReq.current) return;
            setSuggestions(data.suggestions || []);
            setSuggestLang(data.language || '');
        } catch (err) {
            if (reqId !== suggestReq.current) return;
            setSuggestError(errMsg(err, 'Could not load suggestions.'));
        } finally {
            if (reqId === suggestReq.current) setSuggesting(false);
        }
    };

    // Tell the server whether this chat is on screen -> it skips its own push for people who are reading
    const reportVisibility = (orderId, visible) => {
        const s = socketRef.current;
        if (s?.connected && orderId) s.emit('chat-visibility', { orderId, visible }, () => {});
    };

    useEffect(() => { loadOrders(); }, []);

    // Track tab visibility + window focus
    useEffect(() => {
        const update = () => setWindowActive(isWindowActive());
        window.addEventListener('focus', update);
        window.addEventListener('blur', update);
        document.addEventListener('visibilitychange', update);
        return () => {
            window.removeEventListener('focus', update);
            window.removeEventListener('blur', update);
            document.removeEventListener('visibilitychange', update);
        };
    }, []);

    // This chat is open and in front of the agent -> no sound / desktop popup for it (see ChatNotifier)
    useEffect(() => {
        chatPresence.set(selected && windowActive ? selected.orderId : null);
        return () => chatPresence.set(null);
    }, [selected?.orderId, windowActive]);

    useEffect(() => { reportVisibility(selected?.orderId, windowActive); }, [windowActive]);

    // Opened from a desktop notification -> jump straight to that conversation
    useEffect(() => {
        const wanted = location.state?.orderId;
        if (!wanted) return;
        const match = orders.find((o) => o.orderId === wanted);
        if (match) {
            setSelected(match);
            navigate(location.pathname, { replace: true, state: null });
        }
    }, [location.state, orders]);

    useEffect(() => {
        setMessages([]);
        setMessagesOrderId(null);
        setText('');
        setChain(false);
        editedFromSuggestion.current = false;
        if (selected) loadMessages(selected);
        // join the socket room of the chat that is now open, then say whether it is on screen
        if (selected && socketRef.current?.connected) {
            socketRef.current.emit('join-order', selected.orderId, () => reportVisibility(selected.orderId, windowActiveRef.current));
        }
    }, [selected?.orderId]);

    // Chat is open AND the agent is looking at it -> its customer messages are now read.
    // (Background reloads never mark anything as read, so unread chats stay highlighted.)
    useEffect(() => {
        if (!chatLoaded || !windowActive) return;
        if (!messages.some((m) => m.senderType === 'user' && !m.isRead)) return;
        const orderId = selected.orderId;
        chatApi.markRead(orderId)
            .then(() => {
                if (selectedIdRef.current !== orderId) return;
                setMessages((current) => current.map((m) => (m.senderType === 'user' && !m.isRead ? { ...m, isRead: true } : m)));
            })
            .catch(() => {}); // retried on the next message / when the window gets focus again
    }, [chatLoaded, windowActive, messages, selected?.orderId]);

    // Live updates: new messages and list changes arrive over Socket.IO, no manual refresh needed
    useEffect(() => {
        if (!token) return undefined;
        const socket = io(`${SOCKET_URL}/chat`, { auth: { token }, transports: ['websocket'], reconnection: true });
        socketRef.current = socket;

        const resync = () => {
            const id = selectedIdRef.current;
            loadOrders(true);
            if (id) loadMessages({ orderId: id }, true);
        };

        socket.on('connect', () => {
            setLive(true);
            const id = selectedIdRef.current;
            if (id) socket.emit('join-order', id, () => { reportVisibility(id, windowActiveRef.current); resync(); }); // (re)join, then catch up on anything missed
            else loadOrders(true);
        });
        socket.on('disconnect', () => setLive(false));
        socket.on('connect_error', () => setLive(false));

        socket.on('new-message', (msg) => {
            if (String(msg.orderId) !== selectedIdRef.current) return;
            setMessages((current) => (current.some((m) => m._id === msg._id) ? current : [...current, msg]));
        });
        // any chat got a message -> refresh the conversation list (order, status)
        socket.on('admin-list-refresh', () => loadOrders(true));

        return () => { socket.disconnect(); socketRef.current = null; };
    }, [token]);

    // Safety net: if the live connection is down (or blocked), poll so the page still updates itself
    useEffect(() => {
        if (live) return undefined;
        const t = setInterval(() => {
            if (document.visibilityState !== 'visible') return;
            loadOrders(true);
            if (selectedIdRef.current) loadMessages({ orderId: selectedIdRef.current }, true);
        }, POLL_MS);
        return () => clearInterval(t);
    }, [live]);

    // Order status changes (mechanic assigned, completed...) don't send chat events, so refresh the list now and then
    useEffect(() => {
        const t = setInterval(() => { if (document.visibilityState === 'visible') loadOrders(true); }, 30000);
        return () => clearInterval(t);
    }, []);

    // Coming back to the tab -> catch up immediately
    useEffect(() => {
        const onVisible = () => {
            if (document.visibilityState !== 'visible') return;
            loadOrders(true);
            if (selectedIdRef.current) loadMessages({ orderId: selectedIdRef.current }, true);
        };
        document.addEventListener('visibilitychange', onVisible);
        return () => document.removeEventListener('visibilitychange', onVisible);
    }, []);

    useEffect(() => { endRef.current?.scrollIntoView({ block: 'end' }); }, [messages, selected?.orderId]);

    // New customer message (or switched chat, or follow-up after a sent suggestion) -> ask Gemini for 3 replies.
    useEffect(() => {
        suggestReq.current++; // invalidate anything in flight
        setSuggestions([]);
        setSuggestError('');
        setSuggestLang('');
        setSuggesting(false);
        if (wantsSuggestions) loadSuggestions(selected.orderId);
    }, [selected?.orderId, wantsSuggestions, lastMessage?._id]);

    // Customer spoke again -> a new round starts, follow-up mode ends
    useEffect(() => { if (needsReply) setChain(false); }, [needsReply]);

    // fromSuggestion: keep suggesting follow-ups so the agent can send 2-3 messages one by one
    const sendMessage = async (body, fromSuggestion = false) => {
        const value = body.trim();
        if (!value || !selected || sending) return;
        setSending(true);
        try {
            const message = await chatApi.send(selected.orderId, value);
            // the socket echo may already have added it
            setMessages((current) => (current.some((m) => m._id === message._id) ? current : [...current, message]));
            setChain(fromSuggestion);
            setText('');
            editedFromSuggestion.current = false;
            setError('');
        } catch (err) {
            setError(errMsg(err, 'Could not send message.'));
        } finally {
            setSending(false);
        }
    };

    const send = (event) => { event.preventDefault(); sendMessage(text, editedFromSuggestion.current); };

    // Header bell: ask for permission, or fire a test alert so the agent can check sound + popup
    const alertLabel = alertPerm === 'granted' ? 'Test alert' : alertPerm === 'denied' ? 'Alerts blocked' : alertPerm === 'unsupported' ? 'Alerts unavailable' : 'Enable alerts';
    const handleAlertButton = async () => {
        unlockChatSound();
        setAlertHint('');
        let permission = notificationPermission();
        if (permission === 'default') {
            permission = await requestNotificationPermission();
            setAlertPerm(permission);
        }
        const blocked = notificationBlockedReason();
        if (blocked) setAlertHint(blocked);
        // test: same sound + popup a real customer message would trigger
        notifyNewMessage({ orderId: 'test', title: 'Test alert', body: 'New message alerts are working.', onClick: () => window.focus() });
    };

    // Pencil: drop the suggestion into the input so it can be edited before sending.
    const editSuggestion = (value) => {
        editedFromSuggestion.current = true;
        setText(value);
        requestAnimationFrame(() => {
            const el = inputRef.current;
            if (!el) return;
            el.focus();
            el.setSelectionRange(value.length, value.length);
        });
    };

    const showSuggestionBar = wantsSuggestions && (suggesting || suggestions.length > 0 || suggestError);

    return (
        <div className="space-y-5">
            {/* <div className="flex items-end justify-between">
                <div>
                    <p className="text-sm font-semibold uppercase tracking-[0.18em] text-primary">Communication</p>
                    <h1 className="mt-1 text-3xl font-extrabold text-secondary">Chat support</h1>
                    <p className="mt-1 text-sm text-gray-500">Reply to customers about their service orders.</p>
                </div>
                <button onClick={loadOrders} className="rounded-xl border border-gray-200 bg-white p-2.5 text-gray-600"><RefreshCw size={17} /></button>
            </div> */}

            {error && <div className="rounded-xl bg-red-50 p-3 text-sm text-red-700">{error}</div>}

            <div className="grid h-[calc(125dvh-17rem)] min-h-[480px] grid-rows-[minmax(0,auto)_minmax(0,1fr)] overflow-hidden rounded-2xl border border-gray-200 bg-white shadow-sm lg:grid-cols-[300px_1fr] lg:grid-rows-[minmax(0,1fr)]">
                <aside className="max-h-48 overflow-y-auto border-b border-gray-100 lg:max-h-none lg:border-b-0 lg:border-r">
                    <div className="sticky top-0 z-10 border-b border-gray-100 bg-white px-4 py-4 font-bold text-secondary">Conversations</div>
                    {loading ? (
                        <div className="flex justify-center p-8"><LoaderCircle className="animate-spin text-primary" /></div>
                    ) : orders.map((order) => {
                        const isOpen = selected?.orderId === order.orderId;
                        // the chat the agent is reading right now counts as read
                        const unread = isOpen && windowActive ? 0 : order.unreadCount || 0;
                        return (
                            <button
                                key={order.orderId}
                                onClick={() => setSelected(order)}
                                className={`w-full border-b border-gray-100 px-4 py-4 text-left ${isOpen ? 'bg-amber-50' : 'hover:bg-gray-50'}`}
                            >
                                <div className="flex items-center gap-2">
                                    <p className={`min-w-0 flex-1 truncate text-secondary ${unread > 0 ? 'font-extrabold' : 'font-bold'}`}>{order.customerName || 'Customer'}</p>
                                    {unread > 0 && <span className="h-2.5 w-2.5 shrink-0 rounded-full bg-green-500" aria-label="Unread messages" />}
                                </div>
                                <p className="mt-1 text-xs text-gray-500">Order #{order.orderNumber || order.orderId.slice(-6)}</p>
                                <div className="mt-1.5"><StatusChip status={order.status} /></div>
                            </button>
                        );
                    })}
                    {!loading && !orders.length && <p className="p-6 text-sm text-gray-500">No conversations yet.</p>}
                </aside>

                <section className="flex min-h-0 flex-col">
                    {selected ? (
                        <>
                            <div className="shrink-0 border-b border-gray-100 px-5 py-4">
                                <div className="flex flex-wrap items-center gap-2">
                                    <p className="font-bold text-secondary">{selected.customerName}</p>
                                    <StatusChip status={selected.status} />
                                    <button
                                        type="button"
                                        onClick={handleAlertButton}
                                        className={`ml-auto inline-flex items-center gap-1 rounded-full border px-2 py-0.5 text-[10px] font-semibold ${alertPerm === 'granted' ? 'border-green-200 text-green-700 hover:bg-green-50' : 'border-amber-300 text-amber-700 hover:bg-amber-50'}`}
                                    >
                                        <Bell size={11} /> {alertLabel}
                                    </button>
                                    <span className={`inline-flex items-center gap-1 text-[10px] font-medium ${live ? 'text-green-600' : 'text-gray-400'}`} title={live ? 'Live updates on' : 'Reconnecting - refreshing automatically'}>
                                        <span className={`h-1.5 w-1.5 rounded-full ${live ? 'bg-green-500' : 'bg-gray-300'}`} />{live ? 'Live' : 'Offline'}
                                    </span>
                                </div>
                                <p className="text-xs text-gray-500">Order #{selected.orderNumber || selected.orderId.slice(-6)}</p>
                                {alertHint && <p className="mt-2 rounded-lg bg-amber-50 px-3 py-2 text-xs text-amber-800">{alertHint}</p>}
                            </div>

                            <div className="min-h-0 flex-1 space-y-3 overflow-y-auto bg-gray-50 p-5">
                                {messages.map((message) => (
                                    <div key={message._id} className={`flex ${message.senderType === 'user' ? 'justify-start' : 'justify-end'}`}>
                                        <div className={`max-w-[78%] rounded-2xl px-4 py-3 text-sm ${message.senderType === 'user' ? 'bg-white text-gray-700 shadow-sm' : 'bg-secondary text-white'}`}>
                                            {message.message}
                                            <p className="mt-1 text-[10px] opacity-60">{new Date(message.createdAt).toLocaleString('en-IN')}</p>
                                        </div>
                                    </div>
                                ))}
                                {!messages.length && <p className="py-10 text-center text-sm text-gray-500">No messages in this conversation.</p>}
                                <div ref={endRef} />
                            </div>

                            {showSuggestionBar && (
                                <div className="shrink-0 border-t border-gray-100 bg-white px-4 pt-3">
                                    <div className="mb-2 flex items-center justify-between">
                                        <p className="flex items-center gap-1.5 text-xs font-semibold text-gray-500">
                                            <Sparkles size={13} className="text-primary" /> {needsReply ? 'Suggested replies' : 'Suggested next message'}
                                            {suggestLang && !suggesting && (
                                                <span className="rounded-full bg-amber-100 px-2 py-0.5 text-[10px] font-bold text-secondary">{suggestLang}</span>
                                            )}
                                        </p>
                                        <div className="flex items-center gap-2">
                                            {(suggesting || suggestions.length > 0) && <AiBadge />}
                                            <button
                                                type="button"
                                                onClick={() => loadSuggestions(selected.orderId)}
                                                disabled={suggesting}
                                                title="Regenerate suggestions"
                                                className="rounded-lg p-1 text-gray-400 hover:bg-gray-100 hover:text-gray-600 disabled:opacity-40"
                                            >
                                                <RefreshCw size={13} className={suggesting ? 'animate-spin' : ''} />
                                            </button>
                                        </div>
                                    </div>

                                    {suggesting && (
                                        <div className="flex flex-col gap-2 sm:flex-row">
                                            {[0, 1, 2].map((i) => <div key={i} className="h-10 flex-1 animate-pulse rounded-xl bg-gray-100" />)}
                                        </div>
                                    )}

                                    {!suggesting && suggestError && <p className="pb-1 text-xs text-gray-400">{suggestError}</p>}

                                    {!suggesting && suggestions.length > 0 && (
                                        <div className="flex max-h-40 flex-col gap-2 overflow-y-auto pb-1 sm:flex-row sm:items-stretch">
                                            {suggestions.map((suggestion, i) => (
                                                <div key={i} className="flex flex-1 items-stretch overflow-hidden rounded-xl border border-amber-200 bg-amber-50 text-xs text-secondary">
                                                    <button
                                                        type="button"
                                                        onClick={() => sendMessage(suggestion, true)}
                                                        disabled={sending}
                                                        title="Send this reply"
                                                        className="flex-1 px-3 py-2 text-left leading-snug hover:bg-amber-100 disabled:opacity-50"
                                                    >
                                                        {suggestion}
                                                    </button>
                                                    <button
                                                        type="button"
                                                        onClick={() => editSuggestion(suggestion)}
                                                        title="Edit before sending"
                                                        className="flex shrink-0 items-center border-l border-amber-200 px-2 text-gray-500 hover:bg-amber-100 hover:text-secondary"
                                                    >
                                                        <Pencil size={14} />
                                                    </button>
                                                </div>
                                            ))}
                                        </div>
                                    )}
                                </div>
                            )}

                            <form onSubmit={send} className={`flex shrink-0 gap-2 bg-white p-4 ${showSuggestionBar ? '' : 'border-t border-gray-100'}`}>
                                <input
                                    ref={inputRef}
                                    value={text}
                                    onChange={(e) => setText(e.target.value)}
                                    placeholder="Write a reply..."
                                    className="flex-1 rounded-xl border border-gray-200 px-4 py-3 text-sm outline-none focus:border-primary"
                                />
                                <button disabled={sending || !text.trim()} className="rounded-xl bg-primary px-4 text-secondary disabled:opacity-50"><Send size={17} /></button>
                            </form>
                        </>
                    ) : (
                        <div className="flex flex-1 flex-col items-center justify-center text-gray-400">
                            <MessageCircle size={42} />
                            <p className="mt-3 text-sm">Select a conversation to start.</p>
                        </div>
                    )}
                </section>
            </div>
        </div>
    );
}